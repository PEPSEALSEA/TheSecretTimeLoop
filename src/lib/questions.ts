export const TOTAL_QUESTIONS = QUESTIONS.length

export function getQuestion(index: number): Question | null {
  if (index < 0 || index >= QUESTIONS.length) return null
  return QUESTIONS[index] ?? null
}

export function choiceText(question: Question, id: ChoiceId): string {
  return question.choices.find((c) => c.id === id)?.text ?? id
}

export function isCorrectChoice(
  question: Question,
  id: ChoiceId | null | undefined,
): boolean {
  return Boolean(id && id === question.correctChoice)
}
